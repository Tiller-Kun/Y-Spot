/** Bell curve of typical occupancy around a peak hour. */
function simulateBusyness(peakHour: number, peak: number, spread = 3): number[] {
  return Array.from({ length: 24 }, (_, hour) => {
    const value = 0.05 + (peak - 0.05) * Math.exp(-((hour - peakHour) ** 2) / (2 * spread ** 2));
    return Math.round(value * 100) / 100;
  });
}

